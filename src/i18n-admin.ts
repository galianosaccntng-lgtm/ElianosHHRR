export type AdminLang = 'es' | 'en';

export const ADMIN_LANG_KEY = 'ellianos_admin_lang_pref';

export function getInitialAdminLang(): AdminLang {
  try {
    const saved = localStorage.getItem(ADMIN_LANG_KEY);
    if (saved === 'en' || saved === 'es') return saved;
  } catch {}
  return 'en';
}

export function setSavedAdminLang(lang: AdminLang): void {
  try {
    localStorage.setItem(ADMIN_LANG_KEY, lang);
  } catch {}
}

